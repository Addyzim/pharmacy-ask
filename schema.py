def build_schema(db_path: str) -> str:
    con = sqlite3.connect(db_path)
    parts = []
    tables = [r[0] for r in con.execute(
        "select name from sqlite_master where type='table' order by name")]
    for t in tables:
        n = con.execute(f"select count(*) from {t}").fetchone()[0]
        cols = con.execute(f"PRAGMA table_info({t})").fetchall()
        doc = TABLE_DOCS.get(t, "")
        parts.append(f"TABLE {t}  -- {doc} ({n} строк)")
        for c in cols:
            name, ctype = c[1], c[2] or "TEXT"
            sample = ""
            try:
                vals = [r[0] for r in con.execute(
                    f'select distinct "{name}" from {t} where "{name}" is not null limit 3')]
                if vals and ctype == "TEXT":
                    sample = "  ex: " + ", ".join(str(v)[:28] for v in vals)
            except Exception:
                pass
            parts.append(f"    {name} {ctype}{sample}")
        parts.append("")
    con.close()
    return "\n".join(parts) + "\n" + GLOSSARY
